class ProjectConfig(_Model):
    """Concho project configuration (one file per team)."""

    model_config = ConfigDict(
        extra="forbid",
        title="Concho project_config",
        json_schema_extra={"$schema": SCHEMA_DIALECT, "$id": SCHEMA_ID},
    )

    schema_: str | None = Field(
        default=None,
        alias="$schema",
        description="Optional path/URL of the JSON Schema (for editor support).",
    )
    project: ProjectSection
    tvd: TVDSection
    stv: STVSection
    schedule: ScheduleSection
    agent: AgentSection
    files: FilesSection = Field(default_factory=FilesSection)

    @model_validator(mode="after")
    def _cross_section(self) -> ProjectConfig:
        if self.schedule.target_completion > self.project.completion_date:
            raise ValueError(
                f"schedule.target_completion ({self.schedule.target_completion}) is after "
                f"project.completion_date ({self.project.completion_date})."
            )
        a, b = self.stv.custom_materials_file, self.files.custom_materials
        if a and b and Path(a) != Path(b):
            raise ValueError(
                f"stv.custom_materials_file ('{a}') and files.custom_materials ('{b}') differ; "
                "set one of them or use the same path."
            )
        return self


def json_schema() -> dict[str, Any]:
    """The JSON Schema of ``project_config`` (as checked in under docs/schema/)."""
    schema = ProjectConfig.model_json_schema(by_alias=True)
    # Put $schema/$id first for readability.
    head = {k: schema.pop(k) for k in ("$schema", "$id") if k in schema}
    return {**head, **schema}


def json_schema_text() -> str:
    return json.dumps(json_schema(), indent=2, ensure_ascii=False) + "\n"


