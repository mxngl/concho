class CogenerationSplits(_Model):
    """Shares of the cogeneration fuel per output; must sum to 1.0."""

    electricity: Fraction = Field(description="Share of the fuel used for electricity.")
    heating: Fraction = Field(description="Share of the fuel used for heating.")
    cooling: Fraction = Field(description="Share of the fuel used for cooling.")

    @model_validator(mode="after")
    def _sum_to_one(self) -> CogenerationSplits:
        total = self.electricity + self.heating + self.cooling
        if abs(total - 1.0) > SHARE_SUM_TOLERANCE:
            raise ValueError(
                f"cogeneration splits must sum to 1.0, but they sum to {total:.6f}."
            )
        return self


