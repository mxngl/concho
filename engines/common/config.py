class TVDSection(_Model):
    """Target Value Design: total target, cluster split, custom clusters."""

    total_target: float | None = Field(
        default=None,
        gt=0,
        description="Total target amount. Give this OR `budget` + `target`, not both.",
    )
    budget: Budget | None = Field(
        default=None, description="Course budget formula inputs (requires `target`)."
    )
    target: float | None = Field(
        default=None, gt=0, description="Target set by the team, used together with `budget`."
    )
    cluster_split: ClusterSplit = Field(description="How the total is split into clusters A-H.")
    custom_clusters: list[CustomCluster] = Field(
        default_factory=list, description="Optional non-course clusters."
    )
    target_sum_tolerance: Annotated[float, Field(ge=0, lt=1)] = Field(
        default=0.001,
        description=(
            "Allowed difference between the sum of the cluster targets and the total target, "
            "as a fraction of the total target (0.001 = 0.1 %)."
        ),
    )
    target_sum_override: NonEmptyStr | None = Field(
        default=None,
        description=(
            "Accept cluster targets outside `target_sum_tolerance`: the reason why the "
            "mismatch is intended (e.g. 'targets from an older worksheet, reconciled in "
            "week 6'). null (default) = a mismatch outside the tolerance is an error. The "
            "TVD engine reports the gap with status `override`."
        ),
    )

    @model_validator(mode="after")
    def _check_targets(self) -> TVDSection:
        has_total = self.total_target is not None
        has_budget = self.budget is not None
        if has_total == has_budget:
            raise ValueError(
                "give either total_target (a fixed amount) or budget + target "
                "(course budget formula), not both and not neither."
            )
        if has_budget and self.target is None:
            raise ValueError("budget is set, so target (the team's target amount) is required.")
        if has_total and self.target is not None:
            raise ValueError(
                "target is only used with budget; with total_target, remove target."
            )

        names = [c.name for c in self.custom_clusters]
        reserved = {c.value.lower() for c in CourseCluster} | {
            n.lower() for n in CLUSTER_NAMES.values()
        }
        for name in names:
            if name.lower() in reserved:
                raise ValueError(
                    f"custom cluster '{name}' uses a course cluster letter or name; "
                    "course clusters go into cluster_split."
                )
        dupes = sorted({n for n in names if names.count(n) > 1})
        if dupes:
            raise ValueError(f"custom cluster names must be unique; duplicated: {dupes}.")

        total = self.effective_total
        carved = self.carved_out_total
        if carved > total:
            raise ValueError(
                f"carved-out custom clusters ({_money(carved)}) exceed the total target "
                f"({_money(total)})."
            )
        split = self.cluster_split
        if isinstance(split, ExplicitSplit) and split.basis == "amount":
            course_sum = sum(split.values.values())
            diff = course_sum + carved - total
            if abs(diff) > self.target_sum_tolerance * total and not self.target_sum_override:
                raise ValueError(
                    f"course cluster targets ({_money(course_sum)}) + carved-out custom "
                    f"clusters ({_money(carved)}) = {_money(course_sum + carved)}, which is "
                    f"{_money(abs(diff))} {'above' if diff > 0 else 'below'} the total target "
                    f"{_money(total)} (tolerance {self.target_sum_tolerance:g} = "
                    f"{_money(self.target_sum_tolerance * total)}). Fix the amounts, mark a "
                    "custom cluster as on_top, raise target_sum_tolerance, or accept the "
                    "mismatch with target_sum_override (a reason)."
                )
        return self

    @property
    def effective_total(self) -> float:
        """The total target: `total_target`, or `target` when the budget formula is used."""
        if self.total_target is not None:
            return self.total_target
        assert self.target is not None
        return self.target

    @property
    def carved_out_total(self) -> float:
        return sum(c.target for c in self.custom_clusters if c.mode == "carved_out")

    @property
    def on_top_total(self) -> float:
        return sum(c.target for c in self.custom_clusters if c.mode == "on_top")


