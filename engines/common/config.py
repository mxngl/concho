class UsePhase(_Model):
    """Operational energy and water per year. Every value is required (0 is allowed but must
    be stated) unless `not_modeled` is true."""

    not_modeled: bool = Field(
        default=False,
        description=(
            "true = the use phase is not modeled; the STV result then covers construction "
            "only (reported as a warning). Requires `not_modeled_reason`."
        ),
    )
    not_modeled_reason: str | None = Field(
        default=None,
        description=(
            "Why the use phase is not modeled (required when `not_modeled` is true), e.g. "
            "'no energy model yet'. Reported in the STV results (`use_phase_status`)."
        ),
    )
    grid_kwh: NonNegative | None = Field(default=None, description="Grid electricity (kWh/yr).")
    onsite_renewable_kwh: NonNegative | None = Field(
        default=None, description="On-site renewable electricity, e.g. PV (kWh/yr)."
    )
    natural_gas_m3: NonNegative | None = Field(
        default=None, description="Natural gas (m3/yr)."
    )
    cogeneration: Cogeneration | None = Field(
        default=None,
        description="Cogeneration inputs; the key must be present (`null` = no cogeneration).",
    )
    water: WaterUse | None = Field(default=None, description="Water fixtures and volumes.")

    @model_validator(mode="after")
    def _complete(self) -> UsePhase:
        if self.not_modeled:
            if not (self.not_modeled_reason or "").strip():
                raise ValueError(
                    "use phase is not modeled but not_modeled_reason is missing: say why "
                    "(e.g. 'no energy model yet'), or state every use-phase value."
                )
            return self
        missing = [
            f for f in ("grid_kwh", "onsite_renewable_kwh", "natural_gas_m3")
            if getattr(self, f) is None
        ]
        if "cogeneration" not in self.model_fields_set:
            missing.append("cogeneration")
        if self.water is None:
            missing.append("water")
        else:
            missing += [f"water.{f}" for f in self.water.missing()]
        if missing:
            raise ValueError(
                f"use phase is incomplete; missing: {', '.join(missing)}. State every value "
                "(0 is allowed; cogeneration: null = none; water.urinal_gpf: null = no "
                "urinals) or set not_modeled: true."
            )
        return self

    def has_values(self) -> bool:
        """True if any value is given (used to warn when not_modeled hides values)."""
        return bool(self.model_fields_set - {"not_modeled", "not_modeled_reason"})

    def all_zero(self) -> bool:
        nums = [self.grid_kwh, self.onsite_renewable_kwh, self.natural_gas_m3]
        if self.water is not None:
            nums += [getattr(self.water, f) for f in _WATER_FIELDS]
            nums.append(self.water.urinal_gpf)
        return self.cogeneration is None and all(not v for v in nums)


