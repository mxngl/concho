_SECRET_PATTERNS: list[tuple[str, re.Pattern[str]]] = [
    ("URL with credentials", re.compile(r"[a-z][a-z0-9+.-]*://[^/\s:@]+:[^/\s@]+@", re.I)),
    (
        "URL with a token/key parameter",
        re.compile(
            r"[?&](?:token|access_token|api[_-]?key|apikey|key|secret|password|sig|signature)=",
            re.I,
        ),
    ),
    ("Discord webhook URL", re.compile(r"discord(?:app)?\.com/api/webhooks/", re.I)),
    ("Slack webhook URL", re.compile(r"hooks\.slack\.com/services/", re.I)),
    (
        "webhook URL with UUID",
        re.compile(r"webhook(?:-test)?/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}",
                   re.I),
    ),
    ("GitHub token", re.compile(r"\b(?:gh[pousr]_[A-Za-z0-9]{20,}|github_pat_\w{20,})")),
    ("GitHub raw token", re.compile(r"GHSAT[0-9A-Za-z_]")),
    ("API key (sk-...)", re.compile(r"\bsk-[A-Za-z0-9_-]{16,}")),
    ("Slack token", re.compile(r"\bxox[abprs]-[A-Za-z0-9-]{10,}")),
    ("AWS access key", re.compile(r"\bAKIA[0-9A-Z]{16}\b")),
    ("Google API key", re.compile(r"\bAIza[0-9A-Za-z_-]{30,}")),
    ("JSON web token", re.compile(r"\beyJ[A-Za-z0-9_-]{8,}\.eyJ[A-Za-z0-9_-]{8,}")),
    ("Discord bot token", re.compile(r"\b[MNO][A-Za-z0-9_-]{23,}\.[A-Za-z0-9_-]{6}\.[\w-]{27,}")),
    ("bearer token", re.compile(r"\bBearer\s+[A-Za-z0-9._~+/=-]{16,}")),
    ("private key", re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----")),
    ("Discord ID", re.compile(r"^\s*[0-9]{17,20}\s*$")),
]
# A long opaque string with upper, lower and digits and no spaces/dots/slashes.
_OPAQUE = re.compile(r"^[A-Za-z0-9_\-]{32,}$")


def _looks_opaque(value: str) -> bool:
    return bool(
        _OPAQUE.match(value)
        and re.search(r"[a-z]", value)
        and re.search(r"[A-Z]", value)
        and re.search(r"[0-9]", value)
    )


def find_secrets(data: Any, path: str = "") -> list[str]:
    """Return one error message per value that looks like a secret. Values are not echoed."""
    found: list[str] = []
    if isinstance(data, dict):
        for key, value in data.items():
            sub = f"{path}.{key}" if path else str(key)
            found += find_secrets(str(key), sub + " (key)")
            found += find_secrets(value, sub)
    elif isinstance(data, list):
        for i, value in enumerate(data):
            found += find_secrets(value, f"{path}[{i}]")
    elif isinstance(data, bool):
        pass
    elif isinstance(data, int) and 17 <= len(str(abs(data))) <= 20:
        found.append(_secret_msg(path, "Discord ID"))
    elif isinstance(data, str):
        for label, pattern in _SECRET_PATTERNS:
            if pattern.search(data):
                found.append(_secret_msg(path, label))
                break
        else:
            if _looks_opaque(data):
                found.append(_secret_msg(path, "token-like string"))
    return found


def _secret_msg(path: str, label: str) -> str:
    return (
        f"{path or '<root>'}: value looks like a secret ({label}). Secrets and IDs never go "
        "into project_config: put the value into .env / GitHub secrets and reference it by "
        "env var name (e.g. agent.discord.channels.ask = \"DISCORD_CHANNEL_ID_ASK\")."
    )


