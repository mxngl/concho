class ConfigError(ValueError):
    """Raised by :func:`load_config` when the config has errors."""

    def __init__(self, errors: list[str]):
        self.errors = errors
        super().__init__("invalid project_config:\n" + "\n".join(f"  - {e}" for e in errors))


@dataclass
class ValidationReport:
    config: ProjectConfig | None = None
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.errors


def _format_loc(loc: tuple[Any, ...]) -> str:
    parts: list[str] = []
    for item in loc:
        if isinstance(item, int):
            parts.append(f"[{item}]")
        else:
            # Discriminated-union tags ('explicit', 'derive_from_references') add noise.
            if item in ("explicit", "derive_from_references") and parts:
                continue
            parts.append(("." if parts else "") + str(item))
    return "".join(parts) or "<root>"


def _format_errors(exc: ValidationError) -> list[str]:
    out = []
    for err in exc.errors(include_url=False):
        msg = err["msg"].removeprefix("Value error, ")
        loc = _format_loc(err["loc"])
        if err["type"] == "missing":
            msg = "required field is missing"
        elif err["type"] == "extra_forbidden":
            msg = "unknown field (check the spelling; see docs/config.md)"
        elif err["type"] == "union_tag_invalid":
            msg = (
                "method must be 'explicit' or 'derive_from_references' "
                f"(got {err.get('input', {}).get('method')!r})"
                if isinstance(err.get("input"), dict)
                else msg
            )
        out.append(f"{loc}: {msg}")
    return out


def _check_files(config: ProjectConfig, base_dir: Path, report: ValidationReport) -> None:
    files = config.files
    for name in REQUIRED_FILES:
        rel = getattr(files, name)
        if rel is None:
            report.warnings.append(
                f"files.{name} is not set; the {'TVD' if name == 'cost_db' else 'schedule'} "
                "engine will need it."
            )
        elif not (base_dir / rel).is_file():
            report.errors.append(
                f"files.{name}: file not found: {rel} (resolved to {base_dir / rel}). "
                "Paths are relative to the config file."
            )
    optional = [(f"files.{n}", getattr(files, n)) for n in OPTIONAL_FILES]
    optional.append(("stv.custom_materials_file", config.stv.custom_materials_file))
    for label, rel in optional:
        if rel is not None and not (base_dir / rel).is_file():
            report.warnings.append(
                f"{label}: optional file not found: {rel} (resolved to {base_dir / rel})."
            )
    exports = base_dir / files.exports
    if exports.exists() and not exports.is_dir():
        report.errors.append(f"files.exports: {files.exports} exists but is not a directory.")


def _collect_warnings(config: ProjectConfig, report: ValidationReport) -> None:
    tvd = config.tvd
    total = tvd.effective_total
    cur = config.project.currency

    if tvd.budget is not None:
        budget = tvd.budget.amount
        if total > budget:
            report.warnings.append(
                f"tvd.target ({_money(total)} {cur}) is above the budget from the course "
                f"formula ({_money(budget)} {cur})."
            )

    split = tvd.cluster_split
    if isinstance(split, DeriveFromReferences) and split.reallocation_pct > 0:
        rated = split.owner_ratings.cluster_ratings()
        unrated = [
            c for c, items in rated.items() if not any(r is not None for i in items for r in i)
        ]
        if unrated:
            report.warnings.append(
                f"tvd.cluster_split.owner_ratings: no owner rating for cluster(s) "
                f"{', '.join(unrated)}; they get no owner share."
            )
    if isinstance(split, ExplicitSplit) and split.basis == "amount":
        course_sum = sum(split.values.values())
        diff = course_sum + tvd.carved_out_total - total
        if abs(diff) > ROUNDING_AMOUNT:
            outside = abs(diff) > tvd.target_sum_tolerance * total
            why = (
                f"outside tolerance {tvd.target_sum_tolerance:g}, accepted by "
                f"target_sum_override: {tvd.target_sum_override}"
                if outside
                else f"within tolerance {tvd.target_sum_tolerance:g}"
            )
            report.warnings.append(
                f"tvd.cluster_split: course clusters + carved-out custom clusters sum to "
                f"{_money(course_sum + tvd.carved_out_total)} {cur}, "
                f"{_money(abs(diff))} {'above' if diff > 0 else 'below'} the total target "
                f"{_money(total)} {cur} ({why})."
            )
        all_sum = course_sum + tvd.carved_out_total + tvd.on_top_total
    else:
        all_sum = total + tvd.on_top_total

    on_top = [c for c in tvd.custom_clusters if c.mode == "on_top"]
    if on_top:
        names = ", ".join(f"{c.name} ({_money(c.target)})" for c in on_top)
        report.warnings.append(
            f"tvd.custom_clusters: on-top cluster(s) {names}: all cluster targets sum to "
            f"{_money(all_sum)} {cur}, {_money(all_sum - total)} {cur} above the total target "
            f"{_money(total)} {cur}. Allowed because mode is on_top; these are not course data."
        )

    up = config.stv.use_phase
    if up.not_modeled:
        report.warnings.append(
            "stv.use_phase.not_modeled is true: the STV project result covers construction "
            f"only, while the target covers construction + {config.stv.lifetime_years} years "
            "of operation."
        )
        if up.has_values():
            report.warnings.append(
                "stv.use_phase: values are given but ignored because not_modeled is true."
            )
    else:
        if up.not_modeled_reason:
            report.warnings.append(
                "stv.use_phase: not_modeled_reason is set but ignored because not_modeled is "
                "false."
            )
        if up.all_zero():
            report.warnings.append(
                "stv.use_phase: all use-phase values are 0. If the use phase is not modeled, "
                "set not_modeled: true with a not_modeled_reason instead."
            )

    sched = config.schedule
    for w in sched.blocked_windows:
        if w.end < sched.start_date or w.start > sched.target_completion:
            report.warnings.append(
                f"schedule.blocked_windows: '{w.name}' ({w.start} to {w.end}) lies outside "
                f"the schedule ({sched.start_date} to {sched.target_completion})."
            )
    for h in sched.calendar.holidays:
        if not sched.start_date <= h <= sched.target_completion:
            report.warnings.append(
                f"schedule.calendar.holidays: {h} lies outside the schedule "
                f"({sched.start_date} to {sched.target_completion})."
            )


def validate_config_data(data: Any, base_dir: Path | str = ".") -> ValidationReport:
    """Validate an already parsed config. File paths resolve against ``base_dir``."""
    report = ValidationReport()
    if not isinstance(data, dict):
        report.errors.append("<root>: the config must be a JSON object.")
        return report
    report.errors += find_secrets(data)
    try:
        config = ProjectConfig.model_validate(data)
    except ValidationError as exc:
        report.errors += _format_errors(exc)
        return report
    _collect_warnings(config, report)
    _check_files(config, Path(base_dir), report)
    if report.ok:
        report.config = config
    return report


def validate_config_file(path: Path | str) -> ValidationReport:
    """Read and validate a ``project_config`` JSON file."""
    path = Path(path)
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        return ValidationReport(errors=[f"{path}: cannot read file ({exc.strerror})."])
    try:
        data = json.loads(text)
    except json.JSONDecodeError as exc:
        return ValidationReport(
            errors=[f"{path}:{exc.lineno}:{exc.colno}: invalid JSON ({exc.msg})."]
        )
    return validate_config_data(data, base_dir=path.resolve().parent)


def load_config(path: Path | str) -> ProjectConfig:
    """Load a ``project_config`` file; raise :class:`ConfigError` listing all errors."""
    report = validate_config_file(path)
    if not report.ok:
        raise ConfigError(report.errors)
    assert report.config is not None
    return report.config


