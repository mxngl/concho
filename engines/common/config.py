"""P3.1: ``project_config`` schema, loader and validation.

One JSON file per team describes the project (TVD targets, STV inputs, schedule, agent
settings, file paths). This module defines it as pydantic v2 models, exports the JSON Schema
(``docs/schema/project_config.schema.json``, generated by ``scripts/export_config_schema.py``)
and validates a file beyond types:

- cluster targets sum to the total target within ``tvd.target_sum_tolerance`` (or the
  mismatch is accepted with ``tvd.target_sum_override``)
  (custom clusters: ``carved_out`` counts against the total, ``on_top`` is reported as a
  warning);
- shares/percentages sum to 1.0;
- the STV use phase is complete, or ``not_modeled`` is true;
- dates are in order;
- referenced files exist (warning for optional files);
- no secrets in the file (tokens, URLs with credentials, Discord IDs).

Since P3.2 the TVD and STV engines and the TVD dashboard read their project values from it
(``engines.tvd.targets``, ``engines.stv.project``); the schedule engines follow in P3B.2.

Usage::

    report = validate_config_file("project_config.json")
    if not report.ok:
        print("\\n".join(report.errors))
    config = report.config

    config = load_config("project_config.json")  # raises ConfigError on errors
"""

